# Define an addition function
def addition():

    # Ask the user to enter the first number
    num1 = int(input("Enter first number: "))

    # Ask the user to enter the second number
    num2 = int(input("Enter second number: "))

    # Calculate the sum
    total = num1 + num2

    # Display the result
    print("The sum is:", total)

# Call the function
addition()